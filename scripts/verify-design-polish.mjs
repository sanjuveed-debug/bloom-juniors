import { chromium, expect } from '@playwright/test'
import assert from 'node:assert/strict'
const browser=await chromium.launch({headless:true})
try {
 const page=await browser.newPage({viewport:{width:390,height:844},reducedMotion:'reduce'})
 const errors=[];page.on('pageerror',e=>errors.push(e.message))
 await page.route('**/*',r=>{const u=new URL(r.request().url());return u.hostname==='127.0.0.1'&&!u.pathname.startsWith('/api/')?r.continue():r.abort()})
 const b=name=>page.getByRole('button',{name,exact:true})
 const fit=async()=>assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Horizontal overflow')
 await page.goto('http://127.0.0.1:5173/test-picnic-profile.html')
 await b('Explore').click()
 const arts=await page.locator('[data-activity-art]').evaluateAll(nodes=>nodes.map(n=>n.dataset.activityArt))
 assert.ok(arts.length>=10);assert.equal(new Set(arts).size,arts.length)
 const contrast=await page.locator('.child-tile-label>span').evaluateAll(nodes=>{
  const luminance=color=>{const rgb=color.match(/[\d.]+/g).slice(0,3).map(Number).map(c=>{c/=255;return c<=.04045?c/12.92:((c+.055)/1.055)**2.4});return rgb[0]*.2126+rgb[1]*.7152+rgb[2]*.0722}
  return nodes.map(node=>{let parent=node;while(parent&&['rgba(0, 0, 0, 0)','transparent'].includes(getComputedStyle(parent).backgroundColor))parent=parent.parentElement;const fg=luminance(getComputedStyle(node).color),bg=luminance(getComputedStyle(parent).backgroundColor);return (Math.max(fg,bg)+.05)/(Math.min(fg,bg)+.05)})
 })
 assert.ok(contrast.every(value=>value>=4.5),'Activity descriptions need 4.5:1 contrast')
 await page.screenshot({path:'tmp/design-explore-mobile.png',fullPage:true});await fit()
 await page.setViewportSize({width:1440,height:1000});await page.screenshot({path:'tmp/design-explore-desktop.png',fullPage:true})
 await page.setViewportSize({width:320,height:844});await fit()
 await page.evaluate(()=>document.documentElement.style.fontSize='200%');await fit()
 await page.screenshot({path:'tmp/design-explore-large-text.png',fullPage:true})
 await page.evaluate(()=>document.documentElement.style.fontSize='');await page.setViewportSize({width:390,height:844})
 await page.getByRole('button',{name:/Will it float/}).click()
 await expect(page.locator('.lesson-header')).toBeVisible()
 for(const name of ['Back to adventures','Hear the instructions','Mute automatic voice']){
  const box=await b(name).boundingBox();assert.ok(box.height>=48&&box.width>=48,name)
 }
 await b('Back to adventures').focus();await page.keyboard.press('Tab')
 await expect(b('Hear the instructions')).toBeFocused()
 assert.ok(await b('Hear the instructions').evaluate(el=>getComputedStyle(el).outlineStyle!=='none'))
 await b('Float on top').click()
 const source=page.locator('.float-source');await source.scrollIntoViewIfNeeded()
 const art=await source.locator('[data-drag-art]').boundingBox()
 const x=art.x+art.width*.2,y=art.y+art.height*.3
 await page.mouse.move(x,y);await page.mouse.down();await page.mouse.move(x+28,y+20,{steps:4})
 const ghost=await page.locator('.float-drag-ghost').boundingBox()
 assert.ok(Math.abs(ghost.x-(art.x+28))<2);assert.ok(Math.abs(ghost.y-(art.y+20))<2)
 await page.mouse.up()
 await expect(page.locator('.float-drag-ghost')).toHaveCount(0)
 await expect(b('Put the object in the water')).toBeEnabled()
 await page.evaluate(()=>document.documentElement.style.fontSize='200%');await fit()
 const guide=await page.locator('.float-guide').boundingBox(),tank=await page.locator('.float-tank').boundingBox()
 assert.ok(guide.y+guide.height<=tank.y,'Enlarged instructions overlap experiment')
 await page.screenshot({path:'tmp/design-float-large-text.png',fullPage:true})
 await page.evaluate(()=>document.documentElement.style.fontSize='')
 await b('Back to adventures').click();await b('Explore').click()
 await page.getByRole('button',{name:/Change a shadow/}).click()
 await page.screenshot({path:'tmp/design-shadow-mobile.png',fullPage:true});await fit()
 await page.evaluate(()=>document.documentElement.style.fontSize='200%');await fit()
 await page.screenshot({path:'tmp/design-shadow-large-text.png',fullPage:true})
 assert.deepEqual(errors,[])
 console.log('PASS: distinct Explore artwork, 320px/390px/desktop layout, 200% text layout, shared 48px header controls, off-centre drag anchor and cancel, no runtime errors.')
} finally {await browser.close()}
