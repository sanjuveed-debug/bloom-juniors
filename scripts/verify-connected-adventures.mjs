import { chromium, expect } from '@playwright/test'
import assert from 'node:assert/strict'
import { mkdir } from 'node:fs/promises'
await mkdir('tmp',{recursive:true})
const browser=await chromium.launch({headless:true})
try {
  const page=await browser.newPage({viewport:{width:390,height:844},reducedMotion:'reduce'})
  const errors=[];page.on('pageerror',e=>errors.push(e.message))
  await page.route('**/*',route=>{const u=new URL(route.request().url());return u.hostname !== '127.0.0.1' || u.pathname.startsWith('/api/') ? route.abort() : route.continue()})
  const b=name=>page.getByRole('button',{name,exact:true})
  const launch=async title=>page.getByRole('navigation',{name:'Your picnic adventure path'}).getByRole('button',{name:new RegExp(title)}).click()
  await page.goto('http://127.0.0.1:5173/test-picnic-profile.html')
  await expect(b('Play with Bumi')).toBeVisible({timeout:30000})
  await launch('Pack the Basket')
  await b('Let’s check together ✓').click()
  await expect(page.getByRole('status')).toContainText('Choose something')
  await b('Add one to apples').click()
  await b('Let’s check together ✓').click()
  await expect(page.getByRole('status')).toContainText('needs 2 more')
  await page.reload()
  await launch('Pack the Basket')
  await expect(page.getByLabel('1 placed',{exact:true})).toBeVisible()
  for(let i=0;i<2;i++)await b('Add one to apples').click()
  for(let i=0;i<2;i++)await b('Add one to pears').click()
  await page.screenshot({path:'tmp/basket-mobile.png',fullPage:true})
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth))
  await b('Let’s check together ✓').click();await b('Try a new arrangement →').click()
  await b('Show me how').click()
  await expect(b('Add one to apples')).toBeDisabled()
  await b('Now I’ll try').click()
  await b('Add one to apples').click()
  for(let i=0;i<3;i++)await b('Add one to pears').click()
  await b('Let’s check together ✓').click();await b('Take the idea home →').click()
  await b('Next: Share the Snacks →').click()
  await b('Add one to Pip').click();await b('Add one to Pip').click();await b('Add one to Wren').click()
  await b('Let’s check together ✓').click()
  await expect(page.getByRole('status')).toContainText('Pip has more than one')
  await b('Remove one from Pip').click();await b('Add one to Momo').click()
  await b('Let’s check together ✓').click();await b('Try a new arrangement →').click()
  await page.setViewportSize({width:1280,height:900})
  await page.screenshot({path:'tmp/snacks-desktop.png',fullPage:true})
  for(const name of ['Bo','Momo','Pip','Wren'])await b(`Add one to ${name}`).click()
  await b('Let’s check together ✓').click();await b('Take the idea home →').click()
  await b('Play again').click()
  await expect(page.getByRole('heading',{name:'One for each friend'})).toBeVisible()
  await b('Back to adventures').click();await b('My discoveries').click()
  await expect(page.getByRole('heading',{name:'Pack the Basket',exact:true})).toBeVisible()
  await expect(page.getByRole('heading',{name:'Share the Snacks',exact:true})).toBeVisible()
  await b('Parents').click()
  for(const n of ['1','2','3','4'])await b(n).click()
  await expect(page.getByRole('region',{name:'Pack the Basket learning recap'})).toContainText('used the demonstration')
  await expect(page.getByRole('region',{name:'Share the Snacks learning recap'})).toContainText('tried again')
  const p=await page.evaluate(()=>JSON.parse(localStorage.getItem('yaagvi_progress_v1')))
  assert.equal(p.sessions.filter(s=>['basket-first','snacks-first'].includes(s.activityId)).length,2)
  assert.equal(p.collectionAdventures.basket.state.report.supportedCorrect,2)
  assert.equal(p.totalStars,0)
  assert.deepEqual(errors,[])
  console.log('PASS: two connected adventures, wrong/empty answers, specific hints, demonstration, reload, replay, journal, parent PIN/recaps, mobile fit and no runtime errors; synthetic local profile, external requests blocked.')
}finally{await browser.close()}
