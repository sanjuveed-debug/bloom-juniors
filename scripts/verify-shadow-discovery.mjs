import { chromium, expect } from '@playwright/test'
import assert from 'node:assert/strict'
const origin=process.env.BLOOM_REVIEW_ORIGIN||'http://127.0.0.1:5173'
const browser=await chromium.launch({headless:true})
try{
 const page=await browser.newPage({viewport:{width:390,height:844},hasTouch:true,isMobile:true})
 const errors=[];page.on('pageerror',e=>errors.push(e.message))
 await page.route('**/*',r=>{const u=new URL(r.request().url());return u.origin===origin&&!u.pathname.startsWith('/api/')?r.continue():r.abort()})
 await page.goto(origin+'/play/shadow')
 const b=name=>page.getByRole('button',{name,exact:true})
 await expect(page.getByRole('heading',{name:'How can we change a shadow?'})).toBeVisible()
 await expect(page.getByRole('slider')).toHaveCount(0)
 await page.evaluate(async()=>{const {speechController}=await import('/src/lib/speechController.js');window.spoken=[];speechController.speak=(_o,text)=>window.spoken.push(text)})
 await page.screenshot({path:'tmp/shadow-prediction-mobile.png',fullPage:true})
 await b('Smaller').tap()
 await expect.poll(()=>page.evaluate(()=>window.spoken.at(-1))).toMatch(/Slide the torch/)
 const slider=page.getByRole('slider',{name:'Torch position'})
 const start=Number(await page.locator('[data-shadow-radius]').getAttribute('data-shadow-radius'))
 await slider.focus();await slider.press('ArrowRight')
 assert.ok(Number(await page.locator('[data-shadow-radius]').getAttribute('data-shadow-radius'))>start)
 await expect(page.getByRole('button',{name:'Next experiment'})).toHaveCount(0)
 await slider.press('End')
 await expect(page.getByRole('status')).toContainText('shadow grew')
 await expect.poll(()=>page.evaluate(()=>window.spoken.at(-1))).toMatch(/shadow grew/)
 await page.getByRole('button',{name:'Next experiment'}).click()
 await page.reload();await expect(page.getByRole('status')).toContainText('farther')
 await b('Bigger').tap()
 await page.getByRole('button',{name:'Move farther away'}).tap()
 await expect(page.getByRole('status')).toContainText('became smaller')
 await page.getByRole('button',{name:'Next experiment'}).click()
 await b('It stays').tap();await page.getByRole('button',{name:'Switch off the torch'}).tap()
 await expect(page.locator('[data-shadow-radius]')).toHaveCount(0)
 await page.getByRole('button',{name:'See our discoveries'}).click()
 await expect(page.getByRole('heading',{name:'Small torch. Big discovery.'})).toBeVisible()
 await expect(page.locator('.shadow-journal>div')).toHaveCount(3)
 const saved=await page.evaluate(()=>JSON.parse(localStorage.getItem('bloom_guest_shadow_v1')))
 assert.equal(saved.sessions.length,1)
 await page.reload();await expect(page.locator('.shadow-journal>div')).toHaveCount(3)
 await page.getByRole('slider',{name:'Explore torch position'}).fill('100')
 await b('Switch off the torch').click();await expect(page.locator('[data-shadow-radius]')).toHaveCount(0)
 await b('Switch on the torch').click()
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth))
 await page.screenshot({path:'tmp/shadow-finish-mobile.png',fullPage:true})
 await page.setViewportSize({width:1440,height:1000});await page.emulateMedia({reducedMotion:'reduce'})
 await page.screenshot({path:'tmp/shadow-finish-desktop.png',fullPage:true})
 await b('Play again').click();await expect(b('Bigger')).toBeVisible()
 assert.equal(await page.evaluate(()=>JSON.parse(localStorage.getItem('bloom_guest_shadow_v1')).sessions.length),1)
 await page.goto(origin+'/test-picnic-profile.html')
 await b('Explore').click();await page.getByRole('button',{name:/Change a shadow/}).click()
 for(const prediction of ['Bigger','Smaller','It disappears']){
   await b(prediction).click()
   await page.getByRole('button',{name:/^(Move closer|Move farther away|Switch off the torch)/}).click()
   await page.getByRole('button',{name:/^(Next experiment|See our discoveries)/}).click()
 }
 await b('Finish for now').click();await b('Parents').click();for(const n of ['1','2','3','4'])await b(n).click()
 const recap=page.getByRole('region',{name:'Learning at a glance'})
 await expect(recap).toContainText('Completed all 3 shadow experiments')
 await expect(recap.getByRole('listitem')).toHaveCount(3)
 await page.reload();await b('Parents').click();for(const n of ['1','2','3','4'])await b(n).click()
 await expect(recap).toContainText('Completed all 3 shadow experiments')
 assert.deepEqual(errors,[])
 console.log('PASS: shadow prediction gates, keyboard slider, touch buttons, geometry, narration, three experiments, guest reload/replay, profile Explore/finish/PIN recap/reload, responsive layout and reduced motion; synthetic local data only.')
}finally{await browser.close()}
