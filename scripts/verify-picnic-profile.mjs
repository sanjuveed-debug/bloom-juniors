import { chromium, expect } from '@playwright/test'
import assert from 'node:assert/strict'
import { mkdir } from 'node:fs/promises'

await mkdir('tmp', { recursive: true })
const browser = await chromium.launch({ headless: true })
try {
  const page = await browser.newPage({ viewport: { width: 390, height: 844 } })
  const errors = []
  page.on('pageerror', e => errors.push(e.message))
  await page.route('**/*', route => {
    const u = new URL(route.request().url())
    return u.hostname !== '127.0.0.1' || u.pathname.startsWith('/api/') ? route.abort() : route.continue()
  })
  const button = name => page.getByRole('button', { name: name === 'Take a plate' ? /^Take a plate/ : name, exact: true })
  await page.goto('http://127.0.0.1:5173/test-picnic-profile.html')
  await expect(button('Play with Bumi')).toBeVisible({ timeout: 30000 })
  await page.screenshot({ path: 'tmp/picnic-home-mobile.png', fullPage: true })
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth))
  await button('Play with Bumi').click()
  await button('Ready for our picnic ✓').click()
  await expect(page.getByRole('status')).toContainText('Take a plate')
  await button('Take a plate').click()
  await button("Place plate at Pip's place").click()
  await button('Ready for our picnic ✓').click()
  await expect(page.getByRole('status')).toContainText('still need plates')
  await page.reload()
  await expect(button('Continue adventure')).toBeVisible({ timeout: 30000 })
  await button('Continue adventure').click()
  await expect(button("Remove plate from Pip's place")).toBeVisible()
  await button('Take a plate').click()
  for (const friend of ['Wren', 'Momo', 'Bo']) await button(`Place plate at ${friend}'s place`).click()
  await button('Ready for our picnic ✓').click()
  await button('A new picnic →').click()
  await button('Show me how').click()
  await expect(button('Take a plate')).toBeEnabled({ timeout: 10000 })
  await button('Take a plate').click()
  for (const friend of ['Bo', 'Pip', 'Momo']) await button(`Place plate at ${friend}'s place`).click()
  await button('Ready for our picnic ✓').click()
  await button('Take the idea home →').click()
  await page.screenshot({ path: 'tmp/picnic-finish-mobile.png', fullPage: true })
  await button('Finish for now').click()
  await button('My discoveries').click()
  await expect(page.getByRole('heading', { name: 'The Picnic', exact: true })).toBeVisible()
  await button('Parents').click()
  await expect(page.getByRole('region', { name: 'Picnic learning recap' })).toHaveCount(0)
  for (const n of ['0', '0', '0', '0']) await button(n).click()
  await expect(page.getByText(/Wrong PIN/)).toBeVisible()
  for (const n of ['1', '2', '3', '4']) await button(n).click()
  const summary = page.getByRole('region', { name: 'Picnic learning recap' })
  await expect(summary).toBeVisible()
  await expect(summary).toContainText('used the demonstration')
  await expect(summary).toContainText('tried again without the demonstration')
  const data = await page.evaluate(() => JSON.parse(localStorage.getItem('yaagvi_progress_v1')))
  assert.equal(data.sessions.filter(s => s.activityId === 'picnic-first').length, 1)
  assert.equal(data.picnic.state.report.supportedCorrect, 2)
  assert.equal(data.totalStars, 0)
  assert.deepEqual(errors, [])
  console.log('PASS: mobile home, launch, incorrect feedback, reload/resume, both rounds, demonstration, completion, discoveries, wrong/correct parent PIN and persisted recap; no runtime errors.')
} finally { await browser.close() }
