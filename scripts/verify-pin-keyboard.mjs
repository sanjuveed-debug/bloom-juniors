import { chromium, expect } from '@playwright/test'
import assert from 'node:assert/strict'
const browser = await chromium.launch({ headless: true })
try {
 const page=await browser.newPage({viewport:{width:390,height:844}})
 const errors=[];page.on('pageerror',e=>errors.push(e.message))
 await page.route('**/*',r=>{const u=new URL(r.request().url());return u.hostname==='127.0.0.1'&&!u.pathname.startsWith('/api/')?r.continue():r.abort()})
 await page.goto('http://127.0.0.1:5173/test-account-review.html?mode=pin')
 const pin=page.getByLabel('Parent PIN',{exact:true})
 await pin.fill('12ab');await expect(pin).toHaveValue('12')
 await pin.press('End');await pin.press('Backspace');await expect(pin).toHaveValue('1')
 for(const digit of ['2','3','4'])await page.getByRole('button',{name:digit,exact:true}).click()
 await expect(pin).toHaveValue('1234')
 await expect(pin).toHaveAttribute('type','password')
 await page.getByLabel('Callback outcome').selectOption('slow')
 await pin.press('Enter')
 await expect(pin).toBeDisabled()
 await expect(page.getByRole('button',{name:'Checking...',exact:true})).toBeDisabled()
 await expect(page.getByRole('button',{name:'1',exact:true})).toBeDisabled()
 await page.keyboard.press('Enter');await page.keyboard.press('Enter')
 assert.equal(JSON.parse(await page.locator('pre').innerText()).length,1)
 await expect(pin).toBeEnabled({timeout:5000})
 await expect(pin).toHaveValue('')
 await page.getByLabel('Callback outcome').selectOption('success')
 await pin.fill('4321');await pin.press('Enter')
 assert.equal(JSON.parse(await page.locator('pre').innerText()).length,2)
 await page.screenshot({path:'tmp/pin-keyboard-mobile.png',fullPage:true})
 assert.deepEqual(errors,[])
 console.log('PASS: masked typed PIN, digit filtering, Backspace, mixed keypad/typing, Enter, busy controls, no repeated submission and retry after rejection. Synthetic callbacks; API blocked.')
} finally { await browser.close() }
