import { chromium, expect } from '@playwright/test'
import assert from 'node:assert/strict'

const browser = await chromium.launch({ headless: true })
try {
  const context = await browser.newContext({ viewport: { width: 390, height: 844 }, reducedMotion: 'reduce' })
  await context.route('**/*', route => {
    const url = new URL(route.request().url())
    return url.hostname === '127.0.0.1' && !url.pathname.startsWith('/api/') ? route.continue() : route.abort()
  })
  const page = await context.newPage()
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  const button = name => page.getByRole('button', { name, exact: true })
  const home = page.locator('.child-mission')
  await page.goto('http://127.0.0.1:5173/test-picnic-profile.html')
  await button('Explore').click()
  await page.getByRole('button', { name: /Will it float/ }).click()
  await button('Mute automatic voice').click()
  await button('Float on top').click()
  await page.locator('.float-source').click()
  await button('Put the object in the water').click()
  await page.getByRole('button', { name: /Try the next object/ }).click()
  await button('Back to adventures').click()
  await expect(home).toContainText('CONTINUE YOUR DISCOVERY')
  await expect(home).toContainText('Will it float?')
  await expect(home).toContainText('experiment 2 of 4')
  await page.reload()
  await expect(home).toContainText('experiment 2 of 4')
  await button('Continue adventure').click()
  await expect(page.getByRole('status')).toContainText('pebble')
  await button('Back to adventures').click()
  await button('Explore').click()
  await page.getByRole('button', { name: /Change a shadow/ }).click()
  await expect(page.getByRole('heading', { name: 'How can we change a shadow?' })).toBeVisible()
  if (await button('Mute automatic voice').count()) await button('Mute automatic voice').click()
  await button('Bigger').click()
  await page.getByRole('button', { name: /Move closer/ }).click()
  await page.getByRole('button', { name: /Next experiment/ }).click()
  await button('Back to adventures').click()
  await expect(home).toContainText('Change a shadow')
  await expect(home).toContainText('experiment 2 of 3')
  await page.reload()
  await expect(home).toContainText('Change a shadow')
  await page.screenshot({ path: 'tmp/resume-discovery-mobile.png', fullPage: true })
  await page.setViewportSize({ width: 320, height: 844 })
  await page.evaluate(() => document.documentElement.style.fontSize = '200%')
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
  await page.evaluate(() => document.documentElement.style.fontSize = '')
  await button('Continue adventure').click()
  await expect(page.getByRole('status')).toContainText('farther')
  await button('Smaller').click()
  await page.getByRole('button', { name: /Move farther away/ }).click()
  await page.getByRole('button', { name: /Next experiment/ }).click()
  await button('It disappears').click()
  await page.getByRole('button', { name: /Switch off the torch/ }).click()
  await page.getByRole('button', { name: /See our discoveries/ }).click()
  await button('Back to adventures').click()
  await expect(home).toContainText('Will it float?')
  assert.equal(await page.evaluate(() => JSON.parse(localStorage.getItem('yaagvi_progress_v1')).sessions.filter(session => session.activityId === 'shadow-discovery-first').length), 1)
  assert.deepEqual(errors, [])
  console.log('PASS: water/shadow latest unfinished home card, exact saved round, reload, completed activity removed, older unfinished activity restored, 200% text and one completion record. Synthetic local profile.')
} finally { await browser.close() }
