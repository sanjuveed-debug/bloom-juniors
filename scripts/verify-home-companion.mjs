import { chromium, expect } from '@playwright/test'
import assert from 'node:assert/strict'
const browser = await chromium.launch({headless:true})
try {
 const page = await browser.newPage({viewport:{width:390,height:844}})
 const errors=[]; page.on('pageerror',e=>errors.push(e.message))
 await page.route('**/*',r=>{const u=new URL(r.request().url());return u.hostname==='127.0.0.1'&&!u.pathname.startsWith('/api/')?r.continue():r.abort()})
 await page.goto('http://127.0.0.1:5173/test-picnic-profile.html')
 const hero=page.getByRole('region',{name:'Your next activity'})
 await expect(hero).toBeVisible()
 const heroBox=await hero.boundingBox(),pathBox=await page.getByRole('navigation',{name:'Your picnic adventure path'}).boundingBox()
 assert.ok(heroBox.y<pathBox.y)
 assert.ok((await hero.locator('.child-start').boundingBox()).y<750)
 await page.screenshot({path:'tmp/child-home-focused-mobile.png',fullPage:true})
 await page.getByRole('button',{name:'Explore',exact:true}).click()
 await expect(page.getByRole('heading',{name:'What shall we try?'})).toBeVisible()
 await page.getByRole('button',{name:'Numbers',exact:true}).click()
 await page.getByRole('button',{name:/Share the Snacks/}).click()
 const source=page.getByRole('button',{name:'Take an apple',exact:true})
 const target=page.getByRole('region',{name:"Pip's place"}).locator('.collection-answer')
 await target.scrollIntoViewIfNeeded()
 const a=await source.boundingBox(),b=await target.boundingBox()
 await page.mouse.move(a.x+a.width/2,a.y+a.height/2);await page.mouse.down()
 await page.mouse.move(b.x+b.width/2,b.y+b.height/2,{steps:10})
 await expect(page.getByRole('status')).toContainText('Let go to place it for Pip')
 await expect(page.locator('[data-bumi-state="point"]')).toBeVisible()
 const gaze=await page.locator('[data-bumi-rig]').evaluate(el=>el.style.getPropertyValue('--gaze-y'))
 assert.notEqual(gaze,'0%')
 await page.mouse.up()
 await expect(page.getByRole('status')).toContainText('Pip has 1 apple')
 await expect(page.locator('[data-bumi-state="nod"]')).toBeVisible()
 await page.waitForTimeout(2800)
 await expect(page.locator('[data-bumi-state="idle"]')).toBeVisible()
 await page.emulateMedia({reducedMotion:'reduce'})
 await page.goto('http://127.0.0.1:5173/play')
 await expect(page.locator('[data-bumi-rig]')).toHaveAttribute('data-bumi-paused','true')
 assert.equal(await page.locator('[data-bumi-rig]').evaluate(el=>el.style.getPropertyValue('--gaze-y')),'0%')
 assert.deepEqual(errors,[])
 console.log('PASS: mobile primary activity precedes choices; Explore filtering/launch; active drag gaze and release guidance; placement count/nod resets; reduced motion rests gaze.')
} finally { await browser.close() }
