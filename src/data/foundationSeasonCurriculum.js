function createLesson({
  id, question, visual, accent, surface, strands, arcs,
  claim, claimSymbol, alternatives, story, clues, explanation,
  offline, parentQuestion, toddler, reviewCategory = '', familyMission = false,
}) {
  return {
    id,
    question,
    shortQuestion: question,
    visual,
    accent,
    surface,
    strands,
    arcs,
    predictions: [
      { id: 'claim', label: claim, symbol: claimSymbol },
      ...alternatives.map((label, index) => ({
        id: `alternative-${index + 1}`,
        label,
        symbol: index === 0 ? '🤔' : '💭',
      })),
    ],
    story,
    activityPrompt: familyMission ? 'Collect the three parts of this family mission' : 'Inspect the three connected clues',
    clues: clues.map(([symbol, label], index) => ({ id: `clue-${index + 1}`, symbol, label })),
    explanation,
    offline,
    parentQuestion,
    toddler: {
      question: toddler.question,
      story: toddler.story,
      explanation: toddler.explanation,
      offline: toddler.offline,
      predictions: [
        { id: 'claim', label: toddler.guess, symbol: claimSymbol },
        { id: 'other', label: toddler.other, symbol: '💭' },
      ],
    },
    reviewCategory,
    familyMission,
  }
}

