export function getFoundationSeasonWeekByLesson(lessonId) {
  const weekIndex = FOUNDATION_SEASON_WEEKS.findIndex(week => week.lessonIds.includes(lessonId))
  if (weekIndex < 0) return null
  const week = FOUNDATION_SEASON_WEEKS[weekIndex]
  return {
    ...week,
    weekIndex,
    weekNumber: weekIndex + 1,
    dayIndex: week.lessonIds.indexOf(lessonId),
    dayNumber: week.lessonIds.indexOf(lessonId) + 1,
  }
}
