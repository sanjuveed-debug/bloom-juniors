function lesson({
  id, trailId, question, emoji, colour, prediction, alternatives,
  story, evidence, explanation, activity, parentPrompt, arcs,
}) {
  return {
    id,
    trailId,
    question,
    shortQuestion: question,
    emoji,
    colour,
    predictionOptions: [
      { id: 'model', label: prediction, symbol: '💡' },
      ...alternatives.map((label, index) => ({
        id: `alternative-${index + 1}`,
        label,
        symbol: index ? '🔍' : '🤔',
      })),
    ],
    story,
    evidence: evidence.map(([symbol, label], index) => ({
      id: `evidence-${index + 1}`,
      symbol,
      label,
    })),
    explanation,
    activity,
    parentPrompt,
    strands: ['world-systems', 'thinking-communication'],
    arcs,
  }
}

